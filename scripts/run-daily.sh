#!/usr/bin/env bash
# Unattended daily run (started by launchd at 02:00 JST, see scripts/install-launchd.sh).
#
# - brings the code up to date (fast-forward only; the files a run regenerates are reset first),
# - runs `just daily`: new obs, events, state, tiles and series, and a staged copy of the upload (a dry run of publish),
# - never uploads (the Source Cooperative login expires within a day and needs a browser) and never commits,
# - on failure shows a macOS notification; and when the published data are 3 or more days behind it reminds
#   that `source-coop login` and `just publish --upload` are due.
#
# Logs: $RUN_DIR/logs/daily-<date>.log, status: $RUN_DIR/logs/last-run.txt
set -uo pipefail
RUN_DIR="${SNOW_RUN_DIR:-$HOME/snow-hokkaido-run}"
export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:/usr/bin:/bin"
mkdir -p "$RUN_DIR/logs"
cd "$RUN_DIR" || exit 2
LOG="$RUN_DIR/logs/daily-$(date +%Y-%m-%d).log"
LOCK="$RUN_DIR/logs/.lock"

notify() { /usr/bin/osascript -e "display notification \"$1\" with title \"snow-hokkaido\"" >/dev/null 2>&1 || true; }

# one run at a time; a lock older than 6 hours is taken to be stale
if ! mkdir "$LOCK" 2>/dev/null; then
  if [ -n "$(find "$LOCK" -maxdepth 0 -mmin +360 2>/dev/null)" ]; then rmdir "$LOCK" && mkdir "$LOCK"; else echo "another run is active" >> "$LOG"; exit 0; fi
fi
trap 'rmdir "$LOCK" 2>/dev/null' EXIT

start=$(date +%s)
{
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') start"
  git checkout -q -- docs/data 2>&1 || true         # regenerated by every run
  git fetch -q origin 2>&1 && git merge -q --ff-only origin/main 2>&1 || echo "WARNING: could not fast-forward the code"
  just daily "$@"
} >> "$LOG" 2>&1
code=$?
end=$(date +%s)

latest_local=$(ls "$RUN_DIR"/ledger/obs/season=*/ 2>/dev/null | grep -E '^[0-9]{4}-' | sort | tail -1)
latest_remote=$(curl -s -m 30 https://data.source.coop/smartmaps/foil4gr1/snow-hokkaido/view/dates.json | python3 -c "import sys,json; print(json.load(sys.stdin)['obs'][-1])" 2>/dev/null || echo "unknown")
{
  echo "finished: $(date '+%Y-%m-%d %H:%M:%S')"
  echo "exit code: $code"
  echo "seconds: $((end - start))"
  echo "latest obs day (local): $latest_local"
  echo "latest obs day (published): $latest_remote"
} > "$RUN_DIR/logs/last-run.txt"

if [ "$code" -ne 0 ]; then
  notify "日次の取り込みが失敗しました (終了コード $code)。ログ: $LOG"
elif [ "$latest_remote" != "unknown" ] && [ -n "$latest_local" ]; then
  behind=$(python3 -c "from datetime import date; print((date.fromisoformat('$latest_local') - date.fromisoformat('$latest_remote')).days)" 2>/dev/null || echo 0)
  if [ "$behind" -ge 3 ]; then notify "公開が ${behind} 日遅れています。source-coop login のあと just publish --upload を実行してください。"; fi
fi
exit "$code"
