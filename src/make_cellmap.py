"""Build grid/cellmap.tif (muni_index, static_flags) and muni/master.parquet for all of Hokkaido.

One mosaic COG covers a rectangle of z9 tiles at z18 (512x512 cells per z9 tile). A cell belongs to the
municipality whose polygon contains the cell center (rasterization, pixel-center rule). Source polygons:
MLIT N03, treated as WGS84 (JGD2011 differs by well under a cell).
"""
import argparse
import math
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
from pyproj import Geod
from rasterio.features import rasterize
from rasterio.transform import from_origin
from shapely.ops import unary_union

Z = 18
R = 6378137.0
ORIGIN = math.pi * R
CELL_M = 2 * ORIGIN / 2**Z  # cell edge in EPSG:3857 meters
N9 = 2 ** (Z - 9)  # cells per z9 tile edge


def lon_to_x9(lon):
    return (lon + 180) / 360 * 512


def lat_to_y9(lat):
    return (1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2 * 512


def write_area_report(master, path, cols, rows):
    d = master.diff_pct.abs()
    top = master.reindex(d.sort_values(ascending=False).index).head(10)
    lines = [
        "# Municipality area check (all Hokkaido cellmap)",
        "",
        "Cells assigned by center point (rasterization) to N03 polygons (2026-01-01). `area from cells` = sum of per-row ground cell",
        "area; `polygon area` = geodesic area of the dissolved N03 polygon. Generated by `just cellmap`.",
        "",
        "**Not an official-area comparison.** N03 has no area attribute and the official area table (GSI) has not been fetched, so the",
        "official check required by HANDOFF section 6(d) is still **unchecked**. This only verifies the cell assignment against the same polygons.",
        "",
        f"- Mosaic {cols}x{rows} cells; {len(master)} municipality codes (194 = 178 municipalities + 10 Sapporo wards + 6 Northern Territories villages; Sapporo city 01100 is not a code in N03).",
        f"- Land cells {int(master.n_land_cells.sum()):,}. |diff| median {d.median():.3f}%, max {d.max():.2f}%; all {int((d < 1).sum())} of {len(master)} within 1%.",
        "- Water bodies are not masked (no source yet); sea cells = cells outside every municipality.",
        "",
        "Largest differences:",
        "",
        "| code | name | cells | area from cells (km2) | polygon area (km2) | diff % |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in top.itertuples():
        lines.append(f"| {r.muni_code} | {r.name} | {r.n_land_cells:,} | {r.area_km2_cells:.2f} | {r.area_km2_polygon:.2f} | {r.diff_pct:+.2f} |")
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n03", required=True, help="N03 shapefile")
    ap.add_argument("--out", default="ledger")
    ap.add_argument("--valid-from", default="2026-01-01")
    ap.add_argument("--tiles", help="x0/y0/x1/y1 inclusive z9 tile range (default: from N03 extent)")
    a = ap.parse_args()

    gdf = gpd.read_file(a.n03)
    gdf = gdf[gdf["N03_007"].notna()]
    # wards of designated cities carry the city in N03_004 and the ward in N03_005
    gdf = gdf.assign(name=gdf["N03_004"].fillna("") + gdf["N03_005"].fillna(""))
    if a.tiles:
        tx0, ty0, tx1, ty1 = map(int, a.tiles.split("/"))
    else:
        w, s, e, n = gdf.total_bounds
        tx0, tx1 = int(lon_to_x9(w)), int(lon_to_x9(e))
        ty0, ty1 = int(lat_to_y9(n)), int(lat_to_y9(s))
    cols, rows = (tx1 - tx0 + 1) * N9, (ty1 - ty0 + 1) * N9
    west = -ORIGIN + tx0 * N9 * CELL_M
    north = ORIGIN - ty0 * N9 * CELL_M
    transform = from_origin(west, north, CELL_M, CELL_M)

    full = gdf.groupby("N03_007").agg(
        name=("name", "first"), subprefecture=("N03_002", "first"), geometry=("geometry", lambda g: unary_union(list(g)))
    )
    full = gpd.GeoDataFrame(full, geometry="geometry", crs=gdf.crs).reset_index().sort_values("N03_007")
    geod = Geod(ellps="WGS84")
    area_full = [abs(geod.geometry_area_perimeter(g)[0]) / 1e6 for g in full.geometry]
    shapes3857 = full.geometry.to_crs(3857)

    # muni_index is 1-based in code order; 0 = outside every municipality
    assert len(full) < 255
    muni_index = rasterize(
        [(g, i) for i, g in enumerate(shapes3857, start=1)],
        out_shape=(rows, cols), transform=transform, fill=0, dtype="uint8", all_touched=False,
    )

    # N03 has no sea/water polygons: static_flags bit2 (sea) = outside every municipality.
    # bit0 (evergreen) and bit1 (lake) have no source yet (D3, D4) and stay 0.
    flags = np.where(muni_index == 0, 4, 0).astype(np.uint8)

    # ground area of a cell row: (edge * cos(lat))^2, latitude of the row center
    my = ORIGIN - (np.arange(rows) + ty0 * N9 + 0.5) * CELL_M
    lat = np.degrees(2 * np.arctan(np.exp(my / R)) - math.pi / 2)
    row_area = (CELL_M * np.cos(np.radians(lat))) ** 2
    cells = np.bincount(muni_index.ravel(), minlength=len(full) + 1)
    area_cells = np.bincount(
        muni_index.ravel(), weights=np.repeat(row_area, cols), minlength=len(full) + 1
    )
    master = pd.DataFrame(
        {
            "muni_index": np.arange(1, len(full) + 1),
            "muni_code": full["N03_007"].to_numpy(),
            "name": full["name"].to_numpy(),
            "subprefecture": full["subprefecture"].to_numpy(),
            "area_km2_polygon": area_full,
            "n_land_cells": cells[1:],
            "cell_area_m2_mean": area_cells[1:] / np.maximum(cells[1:], 1),
            "area_km2_cells": area_cells[1:] / 1e6,
            "valid_from": a.valid_from,
            "valid_to": None,
            "tabular_row": None,
            "tabular_col": None,
        }
    )
    master["diff_pct"] = 100 * (master["area_km2_cells"] / master["area_km2_polygon"] - 1)

    out = Path(a.out)
    (out / "grid").mkdir(parents=True, exist_ok=True)
    (out / "muni").mkdir(parents=True, exist_ok=True)
    prof = dict(
        driver="COG", width=cols, height=rows, count=2, dtype="uint8", crs="EPSG:3857",
        transform=transform, compress="deflate", blocksize=512, overview_resampling="nearest",
    )
    with rasterio.open(out / "grid" / "cellmap.tif", "w", **prof) as dst:
        dst.write(muni_index, 1)
        dst.write(flags, 2)
        dst.set_band_description(1, "muni_index")
        dst.set_band_description(2, "static_flags")
        dst.update_tags(
            z9_tiles=f"{tx0}/{ty0}/{tx1}/{ty1}", zoom=str(Z), source="MLIT N03", source_version=a.valid_from,
            rule="cell center point-in-polygon (rasterize, center rule); muni_index is 1-based in code order",
            elev_m="not yet",
        )
    master.to_parquet(out / "muni" / "master.parquet", index=False)
    write_area_report(master, Path("docs/muni-area-check.md"), cols, rows)
    print(f"mosaic {cols}x{rows} cells, z9 tiles {tx0}..{tx1} x {ty0}..{ty1}; municipalities {len(full)}")
    print(f"land cells {int(cells[1:].sum()):,} of {cols * rows:,}")
    print("largest |diff_pct|:")
    print(master.reindex(master.diff_pct.abs().sort_values(ascending=False).index)[
        ["muni_code", "name", "area_km2_polygon", "area_km2_cells", "diff_pct", "n_land_cells"]].head(12).round(2).to_string())


if __name__ == "__main__":
    main()
